# this is python file for simple calculating

# here user can perform simple calculations like addition, subtraction, multiplication and division.

num1 = float(input("Enter first number: "))
num2 = float(input("Enter second number: "))

# addition
sum = num1 + num2
print("The sum of", num1, "and", num2, "is:", sum)

# subtraction
subtraction = num1 - num2
print("The difference between", num1, "and", num2, "is:", subtraction)

# multiplication
multi = num1 * num2
print("The product of", num1, "and", num2, "is:", multi)

# division
divide = num1 / num2
print("The quotient of", num1, "and", num2, "is:", divide)

# modulus
modulus = num1 % num2
print("The modulus of", num1, "and", num2, "is:", modulus)